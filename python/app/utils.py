"""
通用工具函数模块
===============

本模块提供项目中多个模块都会用到的公共小工具，目前包含：
1. **追踪ID生成器**：为每次请求/操作生成一个全局唯一的标识，方便在日志中串联同一请求的所有记录
2. **安全错误信息清洗器**：在将错误信息写入日志或返回给前端之前，自动截掉过长的内容，
   并把敏感信息（如密钥、Token）替换为占位符，防止泄露

为什么需要这些工具？
-----------------
- 分布式系统中，一个用户请求可能跨越多个服务（Java后端 → Python模型服务 → 数据库），
  如果没有统一的追踪ID，排查问题时就像"大海捞针"，无法把分散的日志串起来
- 错误信息中可能意外包含数据库密码、API密钥等敏感数据，如果原样写入日志，
  一旦日志被外部访问，就会造成安全漏洞——类比：就像在便利贴上写银行卡密码然后随手贴在显示器上
"""

from __future__ import (
    annotations,  # 启用"延迟求值注解"，让类型注解（如 list[str]）在运行时不被真正执行，提升启动速度
)

import uuid  # Python 内置的唯一ID生成库，类似给每个对象发一张"全球唯一的身份证号"

# ── 安全清洗相关常量 ────────────────────────────────────────────
# 清洗后的错误信息最多保留多少个字符（防止日志被超长错误撑爆）
_SAFE_DETAIL_MAX_LEN = 200

# 硬编码的需要从错误消息中抹掉的敏感关键字（如服务器内部Token）
# 类比：就像阅卷时用修正带把考生的个人信息涂掉一样
_SECRET_TOKEN = "super-secret-token"

# 替换敏感信息时使用的占位符，统一用三个星号，避免暴露原始值长度
_REDACTED = "***"


def create_trace_id() -> str:
    """
    生成一个全局唯一的追踪ID（Trace ID）。

    追踪ID的作用类似于快递单号：一个用户请求从进入系统到最终返回结果，
    沿途经过的所有服务都会在日志中带上同一个追踪ID，排查问题时只要搜索这个ID，
    就能把整条调用链的日志全部串联起来。

    实现细节：
    - 使用 UUID4（基于随机数生成），碰撞概率极低，无需中心化ID分配器
    - 输出格式为 32 位十六进制字符串（如 "a1b2c3d4e5f6..."），不含连字符，方便粘贴和搜索

    Returns:
        str: 32 位十六进制字符串形式的唯一ID
    """
    return uuid.uuid4().hex


def safe_detail(
    exc: Exception | str | None,
    max_len: int = _SAFE_DETAIL_MAX_LEN,
    extra_secrets: list[str] | None = None,
) -> str:
    """
    对错误信息进行"脱敏 + 截断"处理，生成可以安全写入日志或返回前端的字符串。

    做了两件事：
    1. **脱敏**（Redact）：把消息中的敏感关键字（默认 Token + 调用方额外指定的密钥）替换为 "***"
    2. **截断**（Truncate）：如果消息太长（超过 max_len），只保留前 max_len 个字符，
       防止一条异常日志撑爆整个日志文件

    为什么需要脱敏？
    - 想象一下：数据库连接失败时，异常信息可能包含连接字符串，里面有数据库密码。
      如果这条错误信息原封不动地写入日志文件，任何能看到日志的人都能拿到数据库密码——
      这就是"敏感信息泄露"，是 OWASP Top 10 安全风险之一。

    为什么需要截断？
    - 某些异常（如递归爆栈、大对象打印）可能产生几 MB 的错误信息，截断可以防止日志存储被撑爆，
      也避免前端因接收超大响应而卡死

    Args:
        exc: 待清洗的异常对象或错误字符串，传 None 时直接返回空字符串
        max_len: 输出字符串的最大长度（默认 200），超出部分会被切掉
        extra_secrets: 调用方额外指定的敏感字符串列表（如本次请求的临时 Token），
                       这些字符串也会被替换为 "***"

    Returns:
        str: 经过脱敏和截断后的安全错误信息。如果 exc 为 None，返回空字符串 ""
    """
    # 没有异常信息，直接返回空字符串
    if exc is None:
        return ""
    # 统一转为字符串：无论是 Exception 对象还是字符串，都能正确处理
    msg = str(exc)
    # 第一步：替换硬编码的默认敏感关键字
    msg = msg.replace(_SECRET_TOKEN, _REDACTED)
    # 第二步：如果调用方传入了额外的敏感关键字，逐个替换
    if extra_secrets:
        for secret in extra_secrets:
            # 跳过空字符串，防止无意义的替换操作
            if secret:
                msg = msg.replace(secret, _REDACTED)
    # 第三步：截断超长内容——只保留前 max_len 个字符
    # Python 的切片操作对于短字符串是安全的：如果 msg 本来就不足 max_len，切片会返回完整字符串
    return msg[:max_len]
